#!/usr/bin/env node
// Writes web/src/design/registry.gen.ts: one board per state file, so the
// canvas bundle can mount 'inbox/nextStep' and the state test can parse
// every state. Static imports, not import.meta.glob, so every entry is
// typed with no cast. A state file is web/src/pages/<page>/states/<id>.ts;
// the page's index.ts exports `<page>Page`, its PageDefinition.
//   node scripts/genRegistry.ts          write the file
//   node scripts/genRegistry.ts --check  fail when the file is not current
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'

const src = fileURLToPath(new URL('../web/src/', import.meta.url))
const out = join(src, 'design', 'registry.gen.ts')
const check = process.argv.includes('--check')

/**
 * Whether a file in a page's states/ is a state file: not the index, a
 * test or the page's screen map (`screens.ts`, screen review R10).
 */
export function isStateFile(name: string): boolean {
  return name.endsWith('.ts') && name !== 'index.ts' && name !== 'screens.ts' && !name.includes('.test')
}

/** The pages that have states, each with its state ids, sorted. */
export function findBoards(pagesDir: string): { page: string; states: string[] }[] {
  if (!existsSync(pagesDir)) return []
  return readdirSync(pagesDir, { withFileTypes: true })
    .filter((d) => d.isDirectory() && existsSync(join(pagesDir, d.name, 'states')))
    .map((d) => ({
      page: d.name,
      states: readdirSync(join(pagesDir, d.name, 'states'))
        .filter(isStateFile)
        .map((f) => f.slice(0, -3))
        .sort(),
    }))
    .filter((p) => p.states.length > 0)
    .sort((a, b) => a.page.localeCompare(b.page))
}

export function renderRegistry(pages: { page: string; states: string[] }[]): string {
  const imports = pages.map((p) => `import { ${p.page}Page } from '../pages/${p.page}/index.ts'`)
  const ids = pages.flatMap((p) => p.states.map((s) => `${p.page}/${s}`))
  const entries = pages.flatMap((p) => p.states.map((s) => `  board(${p.page}Page, '${s}'),`))
  return [
    '// Generated by scripts/genRegistry.ts. Do not edit; run `pnpm gen:registry`.',
    "import { board, type Board } from '../lib/board.ts'",
    ...imports,
    '',
    '/** Every board of the canvas: one Figma state of one page. */',
    `export type BoardId = ${ids.length === 0 ? 'never' : ids.map((id) => `'${id}'`).join(' | ')}`,
    '',
    'export const boards: readonly Board[] = [',
    ...entries,
    ']',
    '',
  ].join('\n')
}

if (import.meta.main) {
  const text = renderRegistry(findBoards(join(src, 'pages')))
  if (check) {
    const ok = existsSync(out) && readFileSync(out, 'utf8') === text
    console.log(JSON.stringify({ ok, file: 'web/src/design/registry.gen.ts' }))
    if (!ok) console.error('The canvas registry is not current. Run `pnpm gen:registry` and commit the result.')
    process.exitCode = ok ? 0 : 1
  } else {
    writeFileSync(out, text)
    console.log(JSON.stringify({ ok: true, wrote: 'web/src/design/registry.gen.ts' }))
  }
}
